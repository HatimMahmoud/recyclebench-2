#!/usr/bin/env python3
"""tools/gate_rejection_audit.py -- the gate's FALSE-REJECTION rate (exposé P2), from the one store that kept rejected text.

The frozen recycle manifests keep gate scores but not the text of rejected rewordings, so Amendment 1 §A3.2 recorded the
false-rejection rate as not estimable. The compose v2 store (`cache/compose_v2/candidates.jsonl`) keeps every candidate,
admitted or not, generated by the production paraphraser (qwen2.5:3b, the six registered transform classes) and decided by
the production gate (cosine 0.75, BERTScore 0.85, NLI 0.60) against the original request. Its six SINGLE-style conditions
(the anchor's 49 judged fixes x 3 candidates) are the population; style pairs are excluded (two-step rewrites, not the
production operator).

Strata, sampled blind and shuffled together (seed 20261101; registered in prereg Amendment 2 before labelling):
  F  rejected at a SEMANTIC layer (cosine or NLI; BERTScore rejected none)   sample --n-rejected (default 100)
  C  admitted                                                                 sample --n-admitted (default 30)
Rejections at the lexical-divergence layer (near-copies, rejected by design for not being a rewording) are outside the
estimand and are counted, not sampled.

Annotators see only the original request and the rewrite (same rubric as the D5 gate audit). From the two strata,
`invert_stratified` gives P(rejected | preserved) -- the false-rejection rate -- and P(admitted | changed), with bootstrap
intervals, plus the per-layer share of preserved rewordings among the rejected.

  python3 tools/gate_rejection_audit.py export --out audit/gate_rejection
  python3 tools/judge_label_tui.py audit/gate_rejection/rejection_sheet.csv      # fill human_intent_preserved
  python3 tools/gate_rejection_audit.py score --dir audit/gate_rejection
"""
from __future__ import annotations

import argparse
import csv
import json
import random
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from recyclebench.audit import RUBRIC, invert_stratified          # noqa: E402
from recyclebench.datasets import load_jailbreakbench              # noqa: E402
from recyclebench.stats import wilson_interval                     # noqa: E402

STORE = ROOT / "cache" / "compose_v2" / "candidates.jsonl"
SINGLES = ("paraphrase", "syntactic", "lexical", "back_translation", "tense_shift", "register")
SEMANTIC = ("cosine", "bertscore", "nli_entail")
SEED = 20261101
SHEET_COLS = ["row", "original_request", "rewrite", "human_intent_preserved", "note"]
KEY_COLS = ["row", "stratum", "rejected_by", "cond", "bid", "idx", "cosine", "bertscore", "nli_entail"]


def population():
    orig = {b.bid: b.canonical_prompt for b in load_jailbreakbench(ROOT / "data" / "sorrybench.csv")}
    rows = [json.loads(l) for l in STORE.read_text().splitlines() if l.strip()]
    rows = [r for r in rows if r["cond"] in SINGLES and r.get("ok") and r.get("text")]
    for r in rows:
        r["original"] = orig[r["bid"]]
    F = [r for r in rows if not r["admitted"] and r["rejected_by"] in SEMANTIC]
    C = [r for r in rows if r["admitted"]]
    L = [r for r in rows if not r["admitted"] and r["rejected_by"] not in SEMANTIC]
    return F, C, L


def cmd_export(args):
    out = Path(args.out)
    if (out / "rejection_sheet.csv").exists() and not args.force:
        raise SystemExit(f"{out}/rejection_sheet.csv exists -- it may hold labels. Use --force or another --out.")
    F, C, L = population()
    rng = random.Random(args.seed)
    take = [dict(r, stratum="F") for r in rng.sample(F, min(args.n_rejected, len(F)))] + \
           [dict(r, stratum="C") for r in rng.sample(C, min(args.n_admitted, len(C)))]
    rng.shuffle(take)
    out.mkdir(parents=True, exist_ok=True)
    with (out / "rejection_sheet.csv").open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=SHEET_COLS)
        w.writeheader()
        for i, r in enumerate(take, 1):
            w.writerow(dict(row=i, original_request=r["original"], rewrite=r["text"], human_intent_preserved="", note=""))
    with (out / "rejection_key.csv").open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=KEY_COLS)
        w.writeheader()
        for i, r in enumerate(take, 1):
            w.writerow(dict(row=i, stratum=r["stratum"], rejected_by=r["rejected_by"] or "", cond=r["cond"], bid=r["bid"],
                            idx=r["idx"], **{k: r["layers"].get(k, "") for k in SEMANTIC}))
    meta = dict(seed=args.seed, store=str(STORE.relative_to(ROOT)), conditions=list(SINGLES),
                N_F=len(F), N_C=len(C), N_lexical_rejected_unsampled=len(L),
                F_by_layer=dict(Counter(r["rejected_by"] for r in F)),
                n_F=sum(r["stratum"] == "F" for r in take), n_C=sum(r["stratum"] == "C" for r in take))
    (out / "rejection_strata.json").write_text(json.dumps(meta, indent=1))
    (out / "RUBRIC.txt").write_text(RUBRIC)
    print(f"population: {len(F)} rejected at a semantic layer {meta['F_by_layer']}, {len(C)} admitted, "
          f"{len(L)} lexical near-copies (not sampled)")
    print(f"sheet: {len(take)} rows ({meta['n_F']} F + {meta['n_C']} C), shuffled and blind -> {out}/rejection_sheet.csv")


def _wil(k, n):
    w = wilson_interval(k, n)
    return dict(k=k, n=n, rate=round(w.point, 4) if n else None, ci=[round(w.low, 4), round(w.high, 4)] if n else None)


def score(d: Path) -> dict | None:
    sheet, key, strata = d / "rejection_sheet.csv", d / "rejection_key.csv", d / "rejection_strata.json"
    if not (sheet.exists() and key.exists() and strata.exists()):
        return None
    meta = json.loads(strata.read_text())
    keys = {r["row"]: r for r in csv.DictReader(key.open())}
    lab = [(keys[r["row"]], int(r["human_intent_preserved"])) for r in csv.DictReader(sheet.open())
           if (r.get("human_intent_preserved") or "").strip() in ("0", "1")]
    F = [h for k, h in lab if k["stratum"] == "F"]
    C = [h for k, h in lab if k["stratum"] == "C"]
    res = dict(labelled=len(lab), of=meta["n_F"] + meta["n_C"], population=meta,
               preserved_among_rejected=_wil(sum(F), len(F)),
               changed_among_admitted=_wil(len(C) - sum(C), len(C)),
               by_layer={layer: _wil(sum(h for k, h in lab if k["stratum"] == "F" and k["rejected_by"] == layer),
                                     sum(1 for k, _ in lab if k["stratum"] == "F" and k["rejected_by"] == layer))
                         for layer in meta["F_by_layer"]})
    if F and C:
        fa, fr = invert_stratified(meta["N_C"], meta["N_F"], (len(C) - sum(C)) / len(C), sum(F) / len(F), len(C), len(F),
                                   n_boot=4000, seed=11)
        res["false_admission_P(admitted|changed)"] = dict(rate=round(fa.point, 4), ci=[round(fa.low, 4), round(fa.high, 4)])
        res["false_rejection_P(rejected|preserved)"] = dict(rate=round(fr.point, 4), ci=[round(fr.low, 4), round(fr.high, 4)])
    res["scope"] = ("compose v2 single-style candidates of the anchor's 49 fixes; lexical near-copy rejections excluded "
                    "by design; the production manifests' own rejected text was not stored")
    return res


def cmd_score(args):
    d = Path(args.dir)
    res = score(d)
    if res is None:
        raise SystemExit(f"no sheet/key/strata in {d}")
    (d / "rejection_audit_result.json").write_text(json.dumps(res, indent=1))
    print(json.dumps({k: v for k, v in res.items() if k != "population"}, indent=1))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    e = sub.add_parser("export")
    e.add_argument("--out", default="audit/gate_rejection")
    e.add_argument("--n-rejected", type=int, default=100)
    e.add_argument("--n-admitted", type=int, default=30)
    e.add_argument("--seed", type=int, default=SEED)
    e.add_argument("--force", action="store_true")
    s = sub.add_parser("score")
    s.add_argument("--dir", default="audit/gate_rejection")
    args = ap.parse_args(argv)
    {"export": cmd_export, "score": cmd_score}[args.cmd](args)
    return 0


if __name__ == "__main__":
    sys.exit(main())
