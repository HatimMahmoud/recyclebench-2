def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="recyclebench", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    pr = sub.add_parser("run", help="full study (RSR primary, PBR backbone)")
    pr.add_argument("--config", default=None)

    pp = sub.add_parser("pilot", help="size |P^-| and apply the decision rule")
    pp.add_argument("--config", default=None)
    pp.add_argument("--n-behaviours", type=int, default=None)

    pv = sub.add_parser("validate", help="Monte-Carlo estimator validation")
    pv.add_argument("--replicates", type=int, default=300)

    pm = sub.add_parser("manifest", help="build + save the frozen reformulation manifest")
    pm.add_argument("--config", default=None)
    pm.add_argument("--out", default=None)

    pg = sub.add_parser("gate-audit", help="gate false-admission/rejection report")
    pg.add_argument("--manifest", default=None)

    pae = sub.add_parser("audit-export", help="sample + export the human annotation sheet")
    pae.add_argument("--config", default=None)
    pae.add_argument("--n", type=int, default=200, help="audit budget (rows)")
    pae.add_argument("--admitted-share", type=float, default=0.7,
                     help="fraction of the budget spent on ADMITTED variants")
    pae.add_argument("--out", default="audit/audit_sheet.csv")

    pai = sub.add_parser("audit-ingest",
                         help="ingest human labels -> gate rates with CIs + sensitivity")
    pai.add_argument("sheet", help="the completed annotation CSV")
    pai.add_argument("--config", default=None)

    pf = sub.add_parser("figures", help="render the reporting figures")
    pf.add_argument("--config", default=None)
    pf.add_argument("--outdir", default=None)

    ppg = sub.add_parser("prereg", help="write the frozen pre-registration document")
    ppg.add_argument("--config", default=None)
    ppg.add_argument("--out", default="PREREGISTRATION.md")
