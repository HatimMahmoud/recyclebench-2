def cmd_validate(args) -> int:
    from .validate import simulate
    rep = simulate(n_rep=args.replicates)
    _hr("INSTRUMENT VALIDATION (Monte-Carlo)")
    print(json.dumps(rep.summary(), indent=2))
    print("\nInterpretation: the raw estimator is biased upward and under-covers; the"
          "\nbundle-level corrected estimator is ~unbiased with near-nominal coverage."
          "\nThe response-level correction remains biased -- it is mis-specified for a"
          "\nbest-of-many union, which is why calibration is done at the bundle level.")
    print("\nRESULT:", "PASS" if rep.passed else "FAIL")
    return 0 if rep.passed else 1


def cmd_manifest(args) -> int:
    from .config import make_rng
    from .datasets import make_synthetic
    from .reformulate import load_reformulator
    from .gate import load_gate
    from .manifest import Manifest
    cfg = Config.load(args.config) if args.config and Path(args.config).exists() else Config()
    rng = make_rng(cfg.seed)
    behaviours = make_synthetic(cfg, rng)
