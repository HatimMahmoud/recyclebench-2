"""Command-line interface.

    recyclebench pilot      -- size |P^-| per lineage pair and apply the decision rule
    recyclebench run        -- full study: manifest, RSR (primary), PBR (backbone), RQ3, RQ5
    recyclebench validate   -- Monte-Carlo check of the estimators (coverage / bias)
    recyclebench manifest   -- build and save the frozen reformulation manifest
    recyclebench gate-audit -- gate false-admission / false-rejection report
    recyclebench version
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from .config import Config
from . import __version__


_SYNTH_BANNER = """
################################################################################
#  SYNTHETIC OUTPUT -- MOCK BACKEND.  NOT A FINDING ABOUT ANY REAL MODEL.      #
#                                                                              #
#  Every number below is generated by a simulator with planted ground truth.    #
#  The behaviours are benign placeholders, the "responses" are the tokens       #
#  [comply]/[refuse], and the lineage is four MockModel objects with tuned      #
#  constants. The model NAMES are labels on those objects, nothing more.        #
#                                                                              #
#  What this run does establish: that the instrument recovers a known truth.    #
#  What it does NOT establish: anything whatsoever about Llama.                 #
#                                                                              #
#  For real estimates:  recyclebench pilot-pminus / run-real  (see README)      #
################################################################################
"""


def _hr(title: str) -> None:
    print("\n" + "=" * 78)
    print(title)
    print("=" * 78)


def _fmt_ci(ci) -> str:
    return f"[{ci[0]:.4f}, {ci[1]:.4f}]" if ci else "n/a"


def cmd_run(args) -> int:
    print(_SYNTH_BANNER)
    from .study import run_study
    cfg = Config.load(args.config) if args.config and Path(args.config).exists() else Config()
    res = run_study(cfg)
    s = res.summary()

    _hr("GATE AUDIT  (intent-preservation; construct validity)")
    ga = s["gate_audit"]
    print(f"variants generated : {ga['n_variants']}   admitted: {ga['n_admitted']} "
          f"(mean {res.manifest.mean_admitted():.2f} per behaviour)")
    print(f"false-admission    : {ga['false_admission_rate']:.4f}  "
          f"({ga['admitted_that_were_changed']} intent-changed variants wrongly admitted)")
    print(f"false-rejection    : {ga['false_rejection_rate']:.4f}")

    _hr("JUDGE CALIBRATION  (behaviour-bundle level is used for the correction)")
    for lvl in ("bundle_level", "response_level"):
        c = s["judge_calibration"][lvl]
        if c:
            print(f"{lvl:15s} se={c['se']:.4f} sp={c['sp']:.4f} kappa={c['kappa']:.4f} "
                  f"n={c['n']} admitted={c['admitted']}")

    _hr("PILOT  ->  PRE-REGISTERED DECISION RULE")
    p = s["pilot"]
    for pair, k in p["pair_sizes"].items():
        flag = "OK" if k >= p["min_p_minus"] else "under-powered"
        print(f"  |P^-|  {pair:<52s} {k:>4d}   {flag}")
    print(f"  pooled |P^-| = {p['pooled_p_minus']}   (min required {p['min_p_minus']})")
    print(f"  DECISION: {p['decision']}")

    _hr("RQ1 (PRIMARY) -- RECYCLING SUCCESS RATE over P^-")
    for r in s["RSR_primary"]:
        if not r["defined"]:
            print(f"  {r['pair']:<52s} RSR undefined (|P^-| = 0)")
            continue
        tag = "" if r["estimable"] else "  [EXPLORATORY: |P^-| below threshold]"
        print(f"  {r['pair']:<52s} |P^-|={r['n_p_minus']:>4d}  recovered={r['k_recovered']:>4d}")
        print(f"      RSR raw={r['RSR_raw']:.4f}  corrected={r['RSR_corrected']:.4f}  "
              f"CI={_fmt_ci(r['CI'])}  McNemar p={r['mcnemar_p']:.4g}{tag}")

    _hr("RQ2 (INTERPRETATION) -- patching vs. generalisation, by harm category")
    for rr in res.rsr:
        if not rr.defined:
            continue
        print(f"  {rr.pair[0]} -> {rr.pair[1]}")
        for cat, d in sorted(rr.by_category.items()):
            if d["rsr"] is None:
                continue
            read = "surface patching" if d["rsr"] >= 0.5 else "consistent w/ generalisation"
            print(f"      {cat:<14s} n={d['n']:>3d}  RSR={d['rsr']:.3f}   {read}")

    _hr("RQ3 -- DRIVERS OF RECOVERY (pooled over P^-, variant level)")
    if s["RQ3_drivers"]:
        import pandas as pd
        t = pd.DataFrame(s["RQ3_drivers"]["table"])
        print(f"method={s['RQ3_drivers']['method']}  n_obs={s['RQ3_drivers']['n_obs']}  "
              f"groups={s['RQ3_drivers']['n_groups']}")
        print(t.to_string(index=False))
    else:
        print("  not estimable (no recovery variation on P^-)")

    _hr("RQ4 (BACKBONE) -- PER-MODEL PARAPHRASE BYPASS RATE over C_M")
    for b in s["PBR_backbone"]:
        print(f"  {b['model']:<26s} |C_M|={b['n_cm']:>4d} resolved={b['n_resolved']:>4d} "
              f"unresolved={b['n_unresolved']:>3d}  PBR raw={b['PBR_raw']:.4f} "
              f"corr={b['PBR_corrected']:.4f} CI={_fmt_ci(b['CI'])}  {b['verdict']}")

    if s["RQ5_defences"]:
        _hr("RQ5 (OPTIONAL) -- DEFENCES vs RECYCLED BYPASS")
        import pandas as pd
        print(pd.DataFrame(s["RQ5_defences"]).to_string(index=False))

    outdir = Path(cfg.results_dir)
    outdir.mkdir(parents=True, exist_ok=True)
    (outdir / "summary.json").write_text(json.dumps(s, indent=2, default=str))
    res.manifest.save(cfg.manifest_path)
    print(f"\n[written] {outdir/'summary.json'}")
    print(f"[written] {cfg.manifest_path}  (frozen reformulation manifest)")
    print("\n" + "-" * 78)
    print("REMINDER: every figure above is SYNTHETIC (mock backend). This run validates the")
    print("instrument against a planted truth; it says nothing about any real model.")
    print("Do not quote these numbers as findings.")
    print("-" * 78)
    return 0


